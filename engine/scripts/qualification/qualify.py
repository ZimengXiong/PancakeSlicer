#!/usr/bin/env python3
import argparse
import gzip
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import zipfile

import geometry

ROOT = Path(__file__).resolve().parent


def digest(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def resource_digest(root):
    value = hashlib.sha256()
    count = 0
    def visit(directory):
        nonlocal count
        for path in sorted(directory.iterdir(), key=lambda item: item.name):
            if path.is_symlink():
                raise RuntimeError(f'Resource symlink: {path}')
            if path.is_dir():
                visit(path)
            elif path.is_file():
                value.update(f'{path.relative_to(root).as_posix()}\0{digest(path)}\n'.encode())
                count += 1
            else:
                raise RuntimeError(f'Nonregular resource: {path}')
    visit(root)
    return value.hexdigest(), count


def write(path, value):
    Path(path).write_text(json.dumps(value, indent=2) + '\n', encoding='utf-8')


def gcode_lines(data):
    lines = data.decode('utf-8').splitlines()
    if len(lines)>1 and lines[0]=='; HEADER_BLOCK_START' and lines[1].startswith('; generated by '):
        del lines[1]
    return lines


def compare_gcode(left, right):
    if left == right:
        return {'identity': 'byte', 'ignored': []}
    a, b = gcode_lines(left), gcode_lines(right)
    if a == b:
        return {'identity': 'normalized', 'rule': 'generated-by header omitted; line endings normalized to LF', 'ignored': ['; generated by'], 'normalized_sha256': hashlib.sha256(('\n'.join(a)+'\n').encode()).hexdigest()}
    numeric = re.compile(r'([XYZIJKRE])(-?(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)(?:[eE][+-]?[0-9]+)?)')
    variations = []
    equivalent = len(a) == len(b)
    for number, (left, right) in enumerate(zip(a, b), 1):
        if left == right:
            continue
        if not re.match(r'^G0?[0123](?:\s|$)', left) or not re.match(r'^G0?[0123](?:\s|$)', right):
            equivalent = False
            break
        left_code, marker, left_comment = left.partition(';')
        right_code, right_marker, right_comment = right.partition(';')
        if (marker, left_comment) != (right_marker, right_comment):
            equivalent = False
            break
        left_values, right_values = numeric.findall(left_code), numeric.findall(right_code)
        if numeric.sub(r'\1#', left_code) != numeric.sub(r'\1#', right_code) or len(left_values) != len(right_values):
            equivalent = False
            break
        for (axis, x), (other_axis, y) in zip(left_values, right_values):
            limit = 1e-5 if axis == 'E' else 1e-4
            delta = abs(float(x)-float(y))
            if axis != other_axis or delta > limit + 1e-12:
                equivalent = False
                break
            if x != y:
                variations.append({'line':number,'axis':axis,'delta':delta})
        if not equivalent:
            break
    if equivalent:
        return {'identity':'normalized',
                'rule':'generated-by header omitted; line endings normalized to LF; same-motion-line XYZ/IJK/R <= 1e-4 mm, E <= 1e-5; every other command, role and config unchanged; accepted motion values replaced by the bound Linux reference values',
                'normalized_sha256':hashlib.sha256(('\n'.join(a)+'\n').encode()).hexdigest(),
                'numeric_differences':len(variations),'maximum_delta':max((v['delta'] for v in variations),default=0),
                'first_differences':variations[:8]}
    return {'identity': 'diff', 'line_count': [len(a), len(b)],
            'first_differences': [{'line': n + 1, 'reference': x[:240], 'candidate': y[:240]}
                                  for n, (x, y) in enumerate(zip(a, b)) if x != y][:8]}


def compare_case(reference, candidate):
    result = {'reference_gcode_sha256': digest(reference/'out.gcode'), 'reference_package_sha256': digest(reference/'out.gcode.3mf'), 'gcode': compare_gcode((reference/'out.gcode').read_bytes(), (candidate/'out.gcode').read_bytes())}
    with zipfile.ZipFile(reference/'out.gcode.3mf') as a, zipfile.ZipFile(candidate/'out.gcode.3mf') as b:
        names_a, names_b = sorted(a.namelist()), sorted(b.namelist())
        entries = {}
        if names_a != names_b:
            result['package'] = {'identity': 'diff', 'reference_entries': names_a, 'candidate_entries': names_b}
            return result
        for name in names_a:
            x, y = a.read(name), b.read(name)
            if name.endswith('.gcode'):
                entries[name] = compare_gcode(x, y)
            elif name.endswith('.gcode.md5') and result['gcode']['identity'] != 'diff':
                entries[name] = {'identity': 'byte' if x == y else 'normalized', 'rule': 'checksum of compared G-code'}
            else:
                entries[name] = {'identity': 'byte' if x == y else 'diff'}
        result['package'] = {'identity': 'diff' if any(v['identity'] == 'diff' for v in entries.values())
                             else 'normalized' if any(v['identity'] == 'normalized' for v in entries.values()) else 'byte',
                             'entries': entries}
    return result


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tool', required=True, type=Path)
    ap.add_argument('--resources', required=True, type=Path)
    ap.add_argument('--engine-source', required=True)
    ap.add_argument('--publication-source')
    ap.add_argument('--output', required=True, type=Path)
    ap.add_argument('--reference', type=Path)
    ap.add_argument('--command-prefix', default='[]')
    args = ap.parse_args()
    command_prefix = json.loads(args.command_prefix)
    if not isinstance(command_prefix, list) or not all(isinstance(item, str) for item in command_prefix):
        ap.error('command prefix must be a JSON array of strings')
    for value in [args.engine_source] + ([args.publication_source] if args.publication_source else []):
        if not re.fullmatch('[0-9a-f]{40}', value):
            ap.error('source identities must be full commit SHAs')
    args.tool, args.resources = args.tool.resolve(), args.resources.resolve()
    args.output = args.output.resolve()
    args.output.mkdir(parents=True, exist_ok=True)
    if args.reference and not args.publication_source:
        ap.error('a candidate qualification requires its publication commit')
    if args.reference:
        prior = json.loads((args.reference/'qualification.json').read_text())
        if prior.get('platform') != {'os':'linux','arch':'x86_64'}:
            ap.error('reference must be the qualified Linux/x86_64 output')
        if prior['engine_source_sha'] != args.engine_source:
            ap.error('reference engine source differs')
    resources_hash, resources_count = resource_digest(args.resources)
    cases = json.loads((ROOT/'fixtures/cases.json').read_text())
    result = {'schema': 1, 'engine_source_sha': args.engine_source, 'publication_main_sha': args.publication_source,
              'binary_sha256': digest(args.tool), 'resources_sha256': resources_hash, 'resource_file_count': resources_count, 'platform': {'os': {'win32':'windows','darwin':'darwin','linux':'linux'}[sys.platform], 'arch': {'AMD64':'x86_64','x86_64':'x86_64','aarch64':'arm64','arm64':'arm64'}[__import__('platform').machine()]},
              'audits': {}, 'identity': {}, 'ready': False}
    write(args.output/'qualification.json', result)
    for name, case in cases.items():
        out = args.output/name
        out.mkdir(exist_ok=True)
        (out/'data').mkdir(exist_ok=True)
        model_name = 'benchy' if name == 'benchy_flat' else name
        model = out/(model_name+'.stl')
        model.write_bytes(gzip.decompress((ROOT/'models'/(model_name+'.stl.gz')).read_bytes()))
        replacements = {'resources': str(args.resources), 'out': str(out), 'model': str(model)}
        argv = [str(args.tool)] + [arg.format(**replacements) for arg in case['argv']]
        env = {**os.environ, 'TZ': 'UTC', 'PYTHONUTF8': '1', 'NONPLANAR_RESOURCES_DIR': str(args.resources), 'NONPLANAR_HEADS_DIR': str(args.resources/'nonplanar/heads'), 'OMP_NUM_THREADS': '1', 'OPENBLAS_NUM_THREADS': '1'}
        write(out/'command.json', argv)
        with (out/'stdout.log').open('w') as stdout, (out/'stderr.log').open('w') as stderr:
            subprocess.run(command_prefix + argv, check=True, stdout=stdout, stderr=stderr, env=env)
        if case['audit_checks']:
            audit = [sys.executable, '-I', '-X', 'utf8', str(ROOT/'scripts/nonplanar_bench/print_check.py'), str(out/'out.gcode'),
                     '--part', name, '--parts', str(ROOT/'fixtures/parts.json'),
                     '--head', str(args.resources/'nonplanar/heads/bambu-a1-mini.json'),
                     '--tool-out', str(out/'tool.json'), '--package', str(out/'out.gcode.3mf'),
                     '--json', str(out/'print_check.json')]
            with (out/'audit.log').open('w') as log:
                subprocess.run(audit, check=True, stdout=log, stderr=subprocess.STDOUT, env=env)
            verifier_command = [str(args.tool), '--verify-gcode', str(out/'out.gcode'), '--profiles', str(args.resources/'profiles')]
            verifier_run = subprocess.run(command_prefix + verifier_command, check=True, capture_output=True, env=env)
            (out/'verifier.txt').write_bytes(verifier_run.stdout)
            (out/'verifier.stderr.txt').write_bytes(verifier_run.stderr)
            verifier_values = dict(re.findall(r'^(clearance_(?:machine_)?hit_moves)[ \t]+(\d+)\r?$', verifier_run.stdout.decode('utf-8'), re.M))
            verifier_hits = int(verifier_values['clearance_hit_moves'])
            machine_hits = int(verifier_values['clearance_machine_hit_moves'])
            verifier = {'command': verifier_command, 'stdout_sha256': digest(out/'verifier.txt'),
                        'hit_moves': verifier_hits, 'machine_hit_moves': machine_hits}
            pc = json.loads((out/'print_check.json').read_text())
            checks = pc['checks']
            passed = sum(v is True or isinstance(v, dict) and v.get('ok', v.get('pass')) is True for v in checks.values())
            contacts = pc['clearance'].get('hit_moves')
            hits = 0 if checks.get('clearance_0_hits') is True else contacts
            good = pc.get('ok') is True and passed == len(checks) == case['audit_checks'] and hits == 0 and verifier_hits == 0 and machine_hits == 0
            result['audits'][name] = {'passed': passed, 'total': len(checks), 'expected': case['audit_checks'],
                                     'hit_moves': hits, 'clearance_hit_moves': hits, 'contact_moves': contacts,
                                     'collision_tolerance': pc['clearance'].get('collision_tolerance'),
                                     'verifier': verifier, 'ok': good, 'gcode_sha256': digest(out/'out.gcode'),
                                     'package_sha256': digest(out/'out.gcode.3mf'), 'report_sha256': digest(out/'print_check.json')}
            write(args.output/'qualification.json', result)
            if not good:
                raise RuntimeError(f'{name}: reference audit failed')
        if args.reference:
            result['identity'][name] = compare_case(args.reference/name, out)
            if name in {'benchy','benchy_flat'}:
                result['identity'][name]['geometry'] = geometry.compare(args.reference/name/'out.gcode',out/'out.gcode')
            write(args.output/'qualification.json', result)
        print(name, json.dumps(result['audits'].get(name, result['identity'].get(name, {}))), flush=True)
    if digest(args.tool) != result['binary_sha256'] or resource_digest(args.resources)[0] != resources_hash:
        raise RuntimeError('Engine or resources changed during qualification')
    result['audits_passed'] = len(result['audits']) == 3 and all(v['ok'] for v in result['audits'].values())
    result['identity_passed'] = bool(args.reference) and result['identity']['benchy_flat']['gcode']['identity'] != 'diff'
    result['cross_platform'] = bool(args.reference) and result['platform'] != prior['platform']
    result['equivalence_passed'] = bool(args.reference) and all(result['identity'][name]['geometry']['passed'] for name in ['benchy_flat','benchy'])
    result['readiness_basis'] = geometry.NOTE if result['cross_platform'] else 'same-platform byte or declared normalized flat Benchy identity'
    result['ready'] = result['audits_passed'] and (result['equivalence_passed'] if result['cross_platform'] else result['identity_passed'])
    write(args.output/'qualification.json', result)
    if args.reference and not result['ready']:
        raise RuntimeError('qualification refused; inspect recorded audits and identity differences')


if __name__ == '__main__':
    main()
